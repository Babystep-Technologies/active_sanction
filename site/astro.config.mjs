// @ts-check
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";

// The documentation site (#103). Nothing here is packaged: the gemspec's
// `dev_only` rule excludes this whole directory, and `spec/licensing_spec.rb`
// fails the build if that ever stops being true. `docs/` is the directory that
// ships inside the gem, and the site links into it rather than copying it --
// two copies of a procedure means one of them is wrong within a release.
export default defineConfig({
  // The canonical URL, and the one setting here that is expensive to change
  // later: every inbound link, every search result and the `canonical` tag on
  // every page are built from it. Moving to a custom domain means changing
  // `site`, dropping the `base`, adding a CNAME to `public/`, and pointing
  // DNS -- worth doing before launch rather than after.
  site: "https://babystep-technologies.github.io",
  base: "/active_sanction",

  // `dist/` rather than Astro's default, to match the sibling project's
  // convention and to keep one obvious thing for the workflow to upload.
  outDir: "./dist",

  integrations: [
    starlight({
      title: "ActiveSanction",
      description:
        "Screen a name against government sanctions lists, in Ruby, in your own process.",

      // The seal reduced to a ring, a gem and an open ledger. The full seal is
      // `public/logo.svg` and is unreadable at the 32px the header gives it --
      // the motto alone is 21 letters around a circle. One file serves as the
      // header mark and the favicon both, so the two can never drift.
      logo: { src: "./public/logo-mark.svg", alt: "" },
      favicon: "/logo-mark.svg",

      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/Babystep-Technologies/active_sanction",
        },
      ],

      editLink: {
        baseUrl:
          "https://github.com/Babystep-Technologies/active_sanction/edit/main/site/",
      },

      // The navigation is the Diátaxis map, named for what a reader wants
      // rather than for the framework. Nobody arrives at a documentation site
      // wanting a quadrant: the discipline is for whoever writes the pages,
      // the labels are for whoever reads them (#102).
      sidebar: [
        {
          label: "Get started",
          autogenerate: { directory: "tutorial" },
        },
        {
          label: "Guides",
          autogenerate: { directory: "how-to" },
        },
        {
          label: "Reference",
          autogenerate: { directory: "reference" },
        },
        {
          label: "Explanation",
          autogenerate: { directory: "explanation" },
        },
        {
          label: "API docs",
          items: [
            {
              // Generated by `rake doc` and copied under `/api/` during
              // deploy, so Astro never sees these 600 files and has nothing
              // to render. `attrs` keeps it opening in the same tab -- it is
              // part of this site, not somewhere else.
              label: "Generated from the source",
              // Starlight prepends `base` to a sidebar link, unlike a link
              // written in Markdown -- so this is `/api/`, not
              // `/active_sanction/api/`, which would resolve to the base twice.
              link: "/api/",
              attrs: { target: "_self" },
            },
          ],
        },
      ],

      customCss: ["./src/styles/custom.css"],

      // A screening library is not a place to be coy about what it is not,
      // and a reader who lands on one reference table from a search engine
      // never sees the landing page that carries the disclaimer.
      credits: false,
    }),
  ],
});
